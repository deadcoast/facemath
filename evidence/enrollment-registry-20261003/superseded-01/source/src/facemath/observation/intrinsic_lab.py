CONTROL_POINTS = np.array([
    [-.7, 0.], [-.3, 0.], [.3, 0.], [.7, 0.],
    [.02, .65], [-.32, 1.05], [.36, 1.06], [.03, 1.7],
])


def _sample(source: EllipticSource, count: int, rng: np.random.Generator) -> np.ndarray:
    """Interior and boundary points of each error ellipse; no normality assumed."""
    theta = rng.uniform(0, 2*np.pi, (count, 8))
    radius = np.sqrt(rng.uniform(size=(count, 8)))
    radius[:count//2] = 1.
    unit = np.stack((np.cos(theta), np.sin(theta)), axis=-1)*radius[..., None]
    eig, vec = np.linalg.eigh(source.covariance)
    root = (vec*np.sqrt(np.maximum(0., eig))[:, None, :]) @ vec.swapaxes(-1, -2)
    return source.centers+source.quantile*np.einsum('kni,nji->knj', unit, root)


def _exact_relation_batch(points: np.ndarray, specs: tuple) -> np.ndarray:
    """Direct coordinate formulas; this path does not call the interval evaluator."""
    d = np.linalg.norm(np.einsum('n,knd->kd', EYE_VECTOR, points), axis=1)
    values = []
    for spec in specs:
        u = np.einsum('n,knd->kd', spec.a, points)
        v = np.einsum('n,knd->kd', spec.b, points)
        nu, nv = np.linalg.norm(u, axis=1), np.linalg.norm(v, axis=1)
        cross = u[:, 0]*v[:, 1]-u[:, 1]*v[:, 0]
        if spec.family == 'distance':
            value = nu/d
        elif spec.family == 'angle':
            value = np.arctan2(abs(cross), (u*v).sum(axis=1))
        elif spec.family == 'signed_double_area':
            value = cross/(d*d)
        else:
            value = (nu-nv)/(nu+nv)
        values.append(value)
    return np.stack(values, axis=1)


def _so2_minimum(a: np.ndarray, b: np.ndarray) -> float:
    """Independent trace/hypot solution, not the instrument's SVD fit."""
    x = (a-a.mean(axis=0))/np.linalg.norm(EYE_VECTOR@a)
    y = (b-b.mean(axis=0))/np.linalg.norm(EYE_VECTOR@b)
    matrix = x.T@y
    best = np.hypot(matrix[0, 0]+matrix[1, 1], matrix[1, 0]-matrix[0, 1])
    return float(np.sqrt(max(0., (np.sum(x*x)+np.sum(y*y)-2*best)/8)))


def run_set_controls(destination: str | Path, *, seed: int = 26091, samples: int = 1024) -> dict[str, Any]:
    root = Path(destination)
    root.mkdir(parents=True, exist_ok=False)
    if type(samples) is not int or samples < 64 or samples > 100000:
        raise ObservationError('set control sample count must be an integer in [64,100000]')
    rng = np.random.default_rng(seed)
    points_b = CONTROL_POINTS.copy()
    points_b[5, 0] -= .14
    points_b[6, 0] += .14
    factor_a, factor_b = rng.normal(size=(2, 8, 2, 2))*.009
    sa = EllipticSource(CONTROL_POINTS, factor_a@factor_a.swapaxes(-1, -2), np.ones(8, bool), 1.7)
    sb = EllipticSource(points_b, factor_b@factor_b.swapaxes(-1, -2), np.ones(8, bool), 1.7)
    ea, eb = SourceRelations(sa), SourceRelations(sb)
    specs = relation_registry(InstrumentConfig())

    def bound(evaluator: SourceRelations, spec: Any):
        if spec.family == 'distance': return evaluator.length_ratio(spec.a)
        if spec.family == 'angle': return evaluator.angle(spec.a, spec.b)
        if spec.family == 'signed_double_area': return evaluator.signed_area_ratio(spec.a, spec.b)
        return evaluator.asymmetry(spec.a, spec.b)

    intervals = [[bound(e, spec) for spec in specs] for e in (ea, eb)]
    lower = np.array([[i.lower for i in group] for group in intervals])
    upper = np.array([[i.upper for i in group] for group in intervals])
    available = np.array([[i.available for i in group] for group in intervals])
    gap_intervals = [absolute_difference(a, b) for a, b in zip(*intervals)]
    gap_lower = np.array([v.lower for v in gap_intervals])
    gap_upper = np.array([v.upper for v in gap_intervals])
    drawn_a, drawn_b = _sample(sa, samples, rng), _sample(sb, samples, rng)
    values_a, values_b = _exact_relation_batch(drawn_a, specs), _exact_relation_batch(drawn_b, specs)
    gaps = abs(values_a-values_b)
    relation_violation = np.maximum(gap_lower-gaps, gaps-gap_upper)
    shape = bound_refitted_shape(np.stack([sa.centers, sb.centers]), (ea, eb), gap_lower, True)
    refits = np.array([_so2_minimum(a, b) for a, b in zip(drawn_a, drawn_b)])

    # A prespecified admissible eye perturbation changes the denominator, while
    # leaving the mouth itself untouched. Freezing the observed eye span fails.
    denominator_cov = np.zeros((8, 2, 2))
    denominator_cov[:4, 0, 0] = .1**2
    ns = EllipticSource(CONTROL_POINTS, denominator_cov, np.ones(8, bool), 1.)
    ne = SourceRelations(ns)
    altered = CONTROL_POINTS.copy()
    altered[:2, 0] += .1
    altered[2:4, 0] -= .1
    mouth = displacement(6, 5)
    frozen_value = np.linalg.norm(mouth@altered)/np.linalg.norm(EYE_VECTOR@CONTROL_POINTS)
    true_value = np.linalg.norm(mouth@altered)/np.linalg.norm(EYE_VECTOR@altered)
    ratio_range = ne.length_ratio(mouth)

    mirror = CONTROL_POINTS*np.array([-1., 1.])
    dist_a = np.linalg.norm(CONTROL_POINTS[:, None]-CONTROL_POINTS[None, :], axis=-1)
    dist_b = np.linalg.norm(mirror[:, None]-mirror[None, :], axis=-1)
    exact_a, exact_b = replace(sa, quantile=0.), replace(sb, quantile=0.)
    qa, qb = SourceRelations(exact_a), SourceRelations(exact_b)
    exact_gaps = np.array([absolute_difference(bound(qa, r), bound(qb, r)).lower for r in specs[:28]])
    exact_shape = bound_refitted_shape(np.stack([sa.centers, sb.centers]), (qa, qb), exact_gaps, True)
    collapsed = SourceRelations(replace(ns, quantile=6.))
    results = {
        'format': 'facemath.intrinsic_set_controls.v6', 'seed': seed,
        'kind': 'analytic_and_synthetic_set_falsification_NOT_HUMAN_DATA',
        'sampled_shape_pairs': samples, 'relation_checks': int(gaps.size),
        'bounded_relation_count': int(np.all(available, axis=0).sum()),
        'sampled_relation_violations': int(np.sum(relation_violation > 1e-11)),
        'sampled_refit_violations': int(np.sum((refits < shape.lower-1e-11) | (refits > shape.upper+1e-11))),
        'refitted_shape_bounds': shape.to_dict(),
        'sampled_refit_range': [float(refits.min()), float(refits.max())],
        'normalizer_counterexample': {
            'frozen_denominator_value': float(frozen_value), 'actual_value': float(true_value),
            'absolute_frozen_error': float(abs(true_value-frozen_value)),
            'propagated_bounds': ratio_range.to_dict(),
            'contains_actual': bool(ratio_range.lower <= true_value <= ratio_range.upper),
        },
        'reflection_control': {'distance_matrix_max_gap': float(abs(dist_a-dist_b).max()),
                               'proper_shape_rms': _so2_minimum(CONTROL_POINTS, mirror)},
        'zero_radius_limit': {'range_width': exact_shape.upper-exact_shape.lower,
                             'true_rms': _so2_minimum(sa.centers, sb.centers)},
        'collapsed_normalizer': {'eye_span': collapsed.eye_span.to_dict(),
                                'mouth_ratio': collapsed.length_ratio(mouth).to_dict()},
        'cancellation': {'same_length_divisor': ne.length_ratio(EYE_VECTOR).to_dict(),
                         'repeated_vector_cross': ne.bilinear(mouth, mouth, 'cross').to_dict()},
        'limitations': ['samples falsify violations but do not prove global containment',
                       'analytic outer bounds, not exact extrema or formally validated interval arithmetic',
                       'product error sets do not assert independent landmarks',
                       'no model inference, human annotations, or population similarity calibration'],
        'array_axes': {'draws_a': '[sample, reference8, xy]', 'draws_b': '[sample, reference8, xy]',
                      'values_a': '[sample, relation256]', 'values_b': '[sample, relation256]',
                      'source_lower': '[source, relation256]', 'source_upper': '[source, relation256]',
                      'refitted_rms': '[sample]', 'relation_gap': '[sample, relation256]'},
    }
    np.savez_compressed(root/'controls.npz', draws_a=drawn_a, draws_b=drawn_b,
        values_a=values_a, values_b=values_b, relation_gap=gaps, refitted_rms=refits,
        source_centers=np.stack([sa.centers, sb.centers]),
        source_covariances=np.stack([sa.covariance, sb.covariance]), quantile=np.array(sa.quantile),
        source_lower=lower, source_upper=upper, source_available=available,
        gap_lower=gap_lower, gap_upper=gap_upper, normalizer_counterexample=altered,
        normalizer_source_centers=CONTROL_POINTS, normalizer_source_covariance=denominator_cov,
        proper_rotation_candidate=shape.candidate_rotation,
        source_normalized_deviation_radii=shape.source_deviation_radii)
    write_json_new(root/'relations.json', {'relations': [r.metadata() for r in specs]})
    write_json_new(root/'results.json', results)
    return results


def _query(seed: int, mouth_expansion_px: float) -> tuple[np.ndarray, Observation, np.ndarray]:
    """Fresh scripted synthetic query; NOT a reused development/calibration source."""
    rng = np.random.default_rng(seed)
    truth = phantom_points()+[20, 20]
    truth[14, 0] -= mouth_expansion_px
    truth[15, 0] += mouth_expansion_px
    image = render_phantom(truth, seed=seed, shape=(280, 320))
    indices = [SEMANTIC_21.index(name) for name in REFERENCE_NAMES]
    prediction = truth+np.array([.55, -.30])
    prediction[indices] = truth[indices] + BETA@ocular_basis(truth[indices]).T + rng.normal(0, .13, (8,2))
    samples = prediction[None]+rng.normal(0, .015, (7,21,2))
    samples[0] = prediction
    observation = Observation(array_digest(image), image.shape[:2], 'semantic21.v1', SEMANTIC_21,
        prediction, samples, 'synthetic_ocular_bias_observer', object_digest(SPEC), .18, 7,
        tuple(f'controlled_perturbation_{j}' for j in range(7)),
        ('scripted bias fixture; not actual learned face inference',), canonical_json(SPEC))
    return image, observation, truth[indices]


def run_intrinsic_laboratory(destination: str | Path, *, seed: int = 26091) -> dict[str, Any]:
    root = Path(destination)
    root.mkdir(parents=True, exist_ok=False)
    controls = run_set_controls(root/'set_controls', seed=seed)
    # Use the inherited frozen acquisition/evaluator/bias calibration without a
    # second implementation or imported fitted reference coordinates.
    spec, executor, _ = make_fixture_study(root/'inputs', seed=seed,
        development=12, calibration=24, evaluation=12, include_excluded=True)
    study = freeze_study(spec, root/'frozen')
    acquired = run_session(study.root, root/'acquisition', executor)
    qualified = finalize_session(root/'acquisition', root/'qualification')
    calibration = BiasCalibration.from_dict(read_json(qualified/'localization_calibration.json'))
    if calibration.quantile is None:
        raise ObservationError('synthetic control calibration unexpectedly unbounded; retain all source records')
    config = InstrumentConfig(canvas_size=224, eye_span_px=70, uncertainty_draws=16,
                              enable_flow=False, edge_samples=16)
    specs = relation_registry(config)
    image_a, observation_a, truth_a = _query(seed+1000, 0.)
    entries, truth_rows, truth_shapes = [], [], []
    for i, expansion in enumerate((0., 4., 8., 12.)):
        image_b, observation_b, truth_b = _query(seed+2000+i, expansion)
        instrument = FacialInstrument(config, localization_calibration=calibration,
            query_groups=(f'query_A_{seed}', f'query_B_{seed}_{i}'), domain=DOMAIN,
            query_lineages=((f'query_source_A_{seed}',), (f'query_source_B_{seed}_{i}',)))
        result = instrument.run(image_a, image_b, observation_a, observation_b)
        bare = FacialInstrument(config).run(image_a, image_b, observation_a, observation_b)
        name = f'pair_{i:02d}_mouth_{expansion:g}px'
        write_bundle(result, root/name, image_a, image_b)
        aa, bb = nominal_values(truth_a, np.ones(8,bool), specs)[0], nominal_values(truth_b, np.ones(8,bool), specs)[0]
        true_gaps = abs(aa-bb)
        true_rms = _so2_minimum(truth_a, truth_b)
        profile = result.intrinsic
        mask = profile.gap_available
        covered = (~mask) | ((true_gaps >= profile.gap_lower-1e-11) & (true_gaps <= profile.gap_upper+1e-11))
        old_arrays = bare.raw_geometry_arrays()
        unchanged = all(np.array_equal(a, result.arrays()[k]) for k,a in old_arrays.items())
        entry = {'pair': name, 'mouth_expansion_per_side_px': expansion,
            'true_reference_proper_shape_rms': true_rms,
            'observed_proper_shape_rms': profile.shape.observed_rms,
            'outer_shape_range': [profile.shape.lower, profile.shape.upper],
            'known_shape_contained': bool(profile.shape.lower <= true_rms+1e-11 and true_rms <= profile.shape.upper+1e-11),
            'finite_relation_count': int(mask.sum()), 'known_relation_violations': int(np.sum(~covered)),
            'raw_array_count_unchanged': len(old_arrays) if unchanged else None,
            'raw_arrays_unchanged': unchanged, 'families': profile.to_dict()['families'],
            'verification': verify_bundle(root/name)}
        entries.append(entry)
        truth_rows.append(np.stack([truth_a,truth_b]))
        truth_shapes.append(true_rms)
    np.savez_compressed(root/'query_ground_truth.npz', source_reference_points=np.stack(truth_rows),
                        true_proper_shape_rms=np.array(truth_shapes))
    summary = {'format': 'facemath.intrinsic_lab.v6', 'seed': seed,
        'kind': 'synthetic_controls_NOT_HUMAN_ACCURACY',
        'prior_study_preserved': {'development_groups': 12, 'calibration_groups': 24, 'evaluation_groups': 12,
                                 'enrolled': acquired['enrolled'], 'outcomes': acquired['outcomes'],
                                 'scripted_calls': executor.calls},
        'selected_quantile': calibration.quantile,
        'heldout_study_coverage': read_json(qualified/'qualification.json')['selected_error_model'],
        'set_controls': controls, 'queries': entries,
        'qualification_verification': verify_qualification_bundle(qualified),
        'environment': environment(),
        'no_population_similarity_score': True,
        'interpretation': 'new structural relations and refit bounds consume the same source observations and independently fitted error model; all known query coordinates are retained; no best-case selection'}
    write_json_new(root/'laboratory.json', summary)
    return summary
